#!/usr/bin/env bash
# Seed the local wp-env with realistic content so the Sybgo widget,
# reports, and recommendation engine have something to render.
#
# Idempotent: safe to re-run; existing posts/users are skipped on conflict.

set -euo pipefail

wp() { npx --yes @wordpress/env run cli wp "$@"; }

echo "  • Creating editors and authors..."
wp user create alice    alice@example.test    --role=editor   --user_pass=password --porcelain >/dev/null 2>&1 || true
wp user create bob      bob@example.test      --role=author   --user_pass=password --porcelain >/dev/null 2>&1 || true
wp user create charlie  charlie@example.test  --role=contributor --user_pass=password --porcelain >/dev/null 2>&1 || true

echo "  • Publishing posts..."
for i in 1 2 3 4 5; do
	wp post create \
		--post_title="Demo post #$i" \
		--post_status=publish \
		--post_content="Demo content for post $i — generated by dev-seed.sh." \
		--porcelain >/dev/null
done

echo "  • Editing an existing post (to trigger post_edited event)..."
LATEST_ID="$(wp post list --post_type=post --posts_per_page=1 --field=ID)"
wp post update "$LATEST_ID" --post_content="Updated content for post $LATEST_ID." >/dev/null

echo "  • Adding a comment..."
wp comment generate --count=2 --post_id="$LATEST_ID" >/dev/null

echo "  • Triggering a PHP notice (to populate the error tracker)..."
wp eval 'trigger_error("Sybgo demo notice from dev-seed.sh", E_USER_NOTICE);' >/dev/null 2>&1 || true
wp eval 'trigger_error("Sybgo demo warning from dev-seed.sh", E_USER_WARNING);' >/dev/null 2>&1 || true

echo "  • Forcing a Sybgo cron tick (daily aggregation)..."
wp cron event run sybgo_aggregate_daily_events >/dev/null 2>&1 || true

echo "  ✓ Seed complete."
